--playing around with window functions
SELECT observed_at, 
  temp_f, 
  dew_point_f, 
  rel_humidity_pct, 
  wind_direction, 
  wind_speed_mph,
  ROUND(AVG(temp_f) OVER(PARTITION BY wind_direction),2) AS avg_temp_per_wind,
  ROUND(AVG(temp_f) OVER() - temp_f,1) AS degrees_overunder_avg,
  RANK() OVER(ORDER BY wind_speed_mph DESC) AS wind_speed_rank,
  ROUND(AVG(temp_f) OVER(ORDER BY id DESC
  ROWS BETWEEN 6 PRECEDING AND CURRENT ROW),1) AS rolling_average_temp
from weather_observations
  ORDER BY id DESC;